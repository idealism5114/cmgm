"""
Lightweight experiment logger.

Saves each run to experiments/EXPERIMENTS.jsonl (one JSON object per model per run)
and updates experiments/SUMMARY.md (human-readable table).

Usage:
    from cmgm.experiment_logger import ExperimentLogger
    logger = ExperimentLogger()
    logger.log_run(config={...}, results=[(model_name, time, metrics_norm, metrics_orig), ...])
"""

import json
import os
from datetime import datetime
from typing import Dict, List, Tuple, Optional

EXPERIMENTS_DIR = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), 'experiments')
JSONL_FILE = os.path.join(EXPERIMENTS_DIR, 'EXPERIMENTS.jsonl')
SUMMARY_FILE = os.path.join(EXPERIMENTS_DIR, 'SUMMARY.md')


class ExperimentLogger:
    def __init__(self, experiment_dir: Optional[str] = None):
        self.experiment_dir = experiment_dir or EXPERIMENTS_DIR
        os.makedirs(self.experiment_dir, exist_ok=True)
        self._timestamp = datetime.now()

    def log_run(self, config: Dict, results: List[Tuple]) -> str:
        """Log a single experiment run.

        Args:
            config: Dict of configuration parameters (method, epochs, batch_size, etc.)
            results: List of (model_name, train_time_sec, metrics_norm, metrics_orig) tuples

        Returns:
            run_id string like "20260527_143022"
        """
        run_id = self._timestamp.strftime('%Y%m%d_%H%M%S')
        run_tag = config.get('tag', '')

        # JSONL: one line per model
        config_snapshot = {k: v for k, v in config.items() if k != 'tag'}
        lines = []
        for model_name, train_time, mn, mo in results:
            record = {
                'run_id': run_id,
                'timestamp': self._timestamp.isoformat(),
                'tag': run_tag,
                'config': config_snapshot,
                'model': model_name,
                'train_time_sec': round(train_time, 2),
                'normalized': {
                    'MAE': float(mn['MAE']),
                    'MSE': float(mn['MSE']),
                    'RMSE': float(mn['RMSE']),
                    'Residual_Mean': float(mn['Residual_Mean']),
                    'Residual_Std': float(mn['Residual_Std']),
                    'Skewness': float(mn['Skewness']),
                },
                'original_price': {
                    'MAE': float(mo['MAE']),
                    'MSE': float(mo['MSE']),
                    'RMSE': float(mo['RMSE']),
                },
            }
            lines.append(record)

        with open(JSONL_FILE, 'a') as f:
            for line in lines:
                f.write(json.dumps(line, ensure_ascii=False) + '\n')

        # Update SUMMARY.md
        self._update_summary(run_id, run_tag, config_snapshot, results)

        tag_str = f' [{run_tag}]' if run_tag else ''
        print(f"\n📋 Experiment {run_id}{tag_str} logged to {JSONL_FILE}")
        return run_id

    def _update_summary(self, run_id: str, tag: str, config: Dict, results: List[Tuple]):
        """Append a markdown table for this run to SUMMARY.md."""
        if not os.path.exists(SUMMARY_FILE):
            self._write_summary_header()

        tag_str = f' **{tag}**' if tag else ''
        with open(SUMMARY_FILE, 'a') as f:
            f.write(f'\n---\n')
            f.write(f'### Run {run_id}{tag_str}\n\n')
            f.write(f'**Config:** `{json.dumps(config, ensure_ascii=False)}`\n\n')
            f.write(f'| Model | Time | MAE (norm) | MSE (norm) | RMSE (norm) | MAE (orig) | MSE (orig) | RMSE (orig) |\n')
            f.write(f'|-------|------|------------|------------|-------------|------------|------------|-------------|\n')
            for name, t, mn, mo in results:
                f.write(f'| {name} | {t:.1f}s | {mn["MAE"]:.6f} | {mn["MSE"]:.6f} | {mn["RMSE"]:.6f} | {mo["MAE"]:.2f} | {mo["MSE"]:.2f} | {mo["RMSE"]:.2f} |\n')
            f.write('\n')

    def _write_summary_header(self):
        with open(SUMMARY_FILE, 'w') as f:
            f.write('# Experiment Summary\n\n')
            f.write('Auto-generated by `ExperimentLogger`.\n\n')

    @staticmethod
    def load_all() -> List[Dict]:
        """Load all experiment records from JSONL as a list of dicts."""
        if not os.path.exists(JSONL_FILE):
            return []
        with open(JSONL_FILE) as f:
            return [json.loads(line) for line in f if line.strip()]

    @staticmethod
    def last_run() -> Optional[List[Dict]]:
        """Get the records from the most recent run_id."""
        records = ExperimentLogger.load_all()
        if not records:
            return None
        last_id = records[-1]['run_id']
        return [r for r in records if r['run_id'] == last_id]
